def crc8_sae_j1850(data: bytes) -> int:
    """
        Вычисляет CRC-8 по алгоритму SAE J1850.

        Характеристики алгоритма:
        - Ширина: 8 бит
        - Полином: 0x1D (x^8 + x^4 + x^3 + x^2 + 1)
        - Начальное значение: 0xFF
        - Рефлексия входа: Нет
        - Рефлексия выхода: Нет
        - Конечный XOR: 0xFF

        Алгоритм работы:
        1. Устанавливает начальное значение CRC = 0xFF
        2. Для каждого байта данных:
           a. Выполняет XOR с текущим CRC
           b. Для каждого из 8 бит:
              - Если старший бит CRC = 1: сдвиг влево и XOR с полиномом
              - Если старший бит CRC = 0: просто сдвиг влево
           c. Результат маскируется до 8 бит (0xFF)
        3. В конце применяет XOR с 0xFF (инверсия)

        Возвращает:
            int: 8-битное значение CRC (0-255)

    """
    crc = 0xFF
    poly = 0x1D

    for byte in data:
        crc ^= byte

        for _ in range(8):
            if crc & 0x80:
                crc = ((crc << 1) ^ poly) & 0xFF
            else:
                crc = (crc << 1) & 0xFF
    return crc ^ 0xFF